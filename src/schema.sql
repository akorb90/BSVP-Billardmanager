-- PostgreSQL application schema, version 13.
CREATE TABLE admin_credentials(id BIGINT PRIMARY KEY CHECK(id=1), password_hash TEXT NOT NULL);

CREATE TABLE audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')), actor TEXT NOT NULL, action TEXT NOT NULL, match_id BIGINT, detail TEXT NOT NULL);

CREATE TABLE branding(id BIGINT PRIMARY KEY CHECK(id=1),club_name TEXT NOT NULL,primary_color TEXT NOT NULL,background TEXT NOT NULL,surface TEXT NOT NULL,text TEXT NOT NULL,logo TEXT,version BIGINT NOT NULL CHECK(version>=0));

CREATE TABLE entity_ids(name TEXT PRIMARY KEY, value BIGINT NOT NULL);

CREATE TABLE event_match_slots(event_id BIGINT NOT NULL,slot BIGINT NOT NULL CHECK(slot BETWEEN 1 AND 10),match_id BIGINT UNIQUE,player_a_id TEXT,player_a2_id TEXT,player_b_id TEXT,player_b2_id TEXT,table_no BIGINT CHECK(table_no BETWEEN 1 AND 20),target BIGINT CHECK(target BETWEEN 1 AND 999),version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),PRIMARY KEY(event_id,slot));

CREATE TABLE event_planning(event_id BIGINT PRIMARY KEY,started BIGINT NOT NULL DEFAULT 0 CHECK(started IN (0,1)),source_id TEXT UNIQUE,metadata TEXT NOT NULL);

CREATE TABLE event_players(event_id BIGINT NOT NULL,player_id TEXT NOT NULL,team_id TEXT,PRIMARY KEY(event_id,player_id));

CREATE TABLE event_teams(event_id BIGINT NOT NULL,team_id TEXT NOT NULL,PRIMARY KEY(event_id,team_id));

CREATE TABLE events(id BIGINT PRIMARY KEY, name TEXT NOT NULL, kind TEXT NOT NULL CHECK(kind IN ('Liga','Turnier')), date TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open','closed')), version BIGINT NOT NULL DEFAULT 0);

CREATE TABLE "matches"(id BIGINT PRIMARY KEY, event_id BIGINT NOT NULL REFERENCES events(id) DEFERRABLE INITIALLY DEFERRED, player_a TEXT NOT NULL, player_b TEXT NOT NULL, discipline TEXT NOT NULL, target BIGINT NOT NULL CHECK(target BETWEEN 1 AND 999), first TEXT NOT NULL CHECK(first IN ('a','b')), table_no BIGINT CHECK(table_no BETWEEN 1 AND 20), a BIGINT NOT NULL DEFAULT 0, b BIGINT NOT NULL DEFAULT 0, status TEXT NOT NULL DEFAULT 'planned' CHECK(status IN ('planned','live','finished')), version BIGINT NOT NULL DEFAULT 0, pin_hash TEXT, auth_version BIGINT NOT NULL DEFAULT 0, lag_winner TEXT CHECK(lag_winner IN ('a','b')), setup_done BIGINT NOT NULL DEFAULT 0, started_at BIGINT, running_since BIGINT, rack_since BIGINT, elapsed_ms BIGINT NOT NULL DEFAULT 0, player_a_id TEXT, player_b_id TEXT, team_a_id TEXT, team_b_id TEXT, team_a_name TEXT, team_b_name TEXT);

CREATE TABLE nuliga_entities(kind TEXT NOT NULL CHECK(kind IN ('player','team')),source_id TEXT NOT NULL,local_id TEXT NOT NULL,snapshot TEXT NOT NULL,PRIMARY KEY(kind,source_id),UNIQUE(kind,local_id));

CREATE TABLE nuliga_schedule_sync(id BIGINT PRIMARY KEY CHECK(id=1),synced_at TEXT NOT NULL,summary TEXT NOT NULL);

CREATE TABLE nuliga_sync(id BIGINT PRIMARY KEY CHECK(id=1),synced_at TEXT NOT NULL,summary TEXT NOT NULL);

CREATE TABLE pin_attempts(table_no BIGINT PRIMARY KEY, count BIGINT NOT NULL, until BIGINT NOT NULL);

CREATE TABLE players(id TEXT PRIMARY KEY,first_name TEXT NOT NULL CHECK(length(trim(first_name)) BETWEEN 1 AND 100),second_name TEXT NOT NULL DEFAULT '' CHECK(length(second_name)<=100),last_name TEXT NOT NULL CHECK(length(trim(last_name)) BETWEEN 1 AND 100),active BIGINT NOT NULL DEFAULT 1 CHECK(active IN (0,1)),version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0), event_id BIGINT);

CREATE TABLE rental_settings(id BIGINT PRIMARY KEY CHECK(id=1), base_cents BIGINT NOT NULL DEFAULT 900, version BIGINT NOT NULL DEFAULT 0);

CREATE TABLE "rentals"(id BIGINT PRIMARY KEY, table_no BIGINT NOT NULL CHECK(table_no BETWEEN 1 AND 20),
      started_at BIGINT NOT NULL, ended_at BIGINT, hourly_cents BIGINT NOT NULL, base_cents BIGINT NOT NULL,
      adjustment_percent DOUBLE PRECISION, duration_ms BIGINT, billed_minutes BIGINT, total_cents BIGINT,
      status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active','finished')), version BIGINT NOT NULL DEFAULT 0);

CREATE TABLE table_settings(id BIGINT PRIMARY KEY CHECK(id=1),table_count BIGINT NOT NULL CHECK(table_count BETWEEN 1 AND 20),version BIGINT NOT NULL CHECK(version>=0));

CREATE TABLE team_players(team_id TEXT NOT NULL,player_id TEXT NOT NULL,PRIMARY KEY(team_id,player_id));

CREATE TABLE teams(id TEXT PRIMARY KEY,name TEXT NOT NULL CHECK(length(trim(name)) BETWEEN 1 AND 100),active BIGINT NOT NULL DEFAULT 1 CHECK(active IN (0,1)),version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0));

CREATE UNIQUE INDEX occupied_table ON matches(table_no) WHERE status='live';

CREATE UNIQUE INDEX rented_table ON rentals(table_no) WHERE status='active';
